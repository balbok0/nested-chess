CREATE TABLE users (
    id TEXT PRIMARY KEY,
    handle TEXT NOT NULL,
    guest BOOLEAN NOT NULL,
    created_ms BIGINT NOT NULL
);
CREATE UNIQUE INDEX users_handle ON users(lower(handle));
CREATE TABLE identities (
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id),
    PRIMARY KEY(issuer,subject)
);
CREATE TABLE sessions (
    hash TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id),
    expires_ms BIGINT NOT NULL
);
CREATE INDEX sessions_expiry ON sessions(expires_ms);
CREATE TABLE auth_flows (
    hash TEXT PRIMARY KEY,
    browser_hash TEXT NOT NULL,
    provider TEXT NOT NULL,
    verifier TEXT NOT NULL,
    nonce TEXT NOT NULL,
    user_id TEXT REFERENCES users(id),
    linking BOOLEAN NOT NULL,
    expires_ms BIGINT NOT NULL
);
CREATE TABLE ratings (
    user_id TEXT NOT NULL REFERENCES users(id),
    pool TEXT NOT NULL,
    rating DOUBLE PRECISION NOT NULL DEFAULT 1500,
    games INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY(user_id,pool)
);
CREATE TABLE games (
    id TEXT PRIMARY KEY,
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    initial_save TEXT NOT NULL,
    checkpoint TEXT NOT NULL,
    white_id TEXT REFERENCES users(id),
    black_id TEXT REFERENCES users(id),
    seq INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL CHECK(status IN ('waiting','active','paused','finished','cancelled')),
    size SMALLINT NOT NULL,
    layout TEXT NOT NULL,
    rated BOOLEAN NOT NULL,
    result TEXT CHECK(result IN ('white','black','draw')),
    reason TEXT,
    white_ms BIGINT,
    black_ms BIGINT,
    increment_ms BIGINT NOT NULL,
    running_since_ms BIGINT,
    deadline_ms BIGINT,
    turn TEXT NOT NULL DEFAULT 'white' CHECK(turn IN ('white','black')),
    ready_white BOOLEAN NOT NULL DEFAULT false,
    ready_black BOOLEAN NOT NULL DEFAULT false,
    created_ms BIGINT NOT NULL,
    CHECK(white_id IS NULL OR black_id IS NULL OR white_id!=black_id)
);
CREATE INDEX games_white ON games(white_id,ordinal DESC);
CREATE INDEX games_black ON games(black_id,ordinal DESC);
CREATE INDEX games_deadline ON games(deadline_ms) WHERE status='active' AND deadline_ms IS NOT NULL;
CREATE INDEX games_queue ON games(created_ms,id) WHERE status='waiting' AND rated;
CREATE TABLE events (
    game_id TEXT NOT NULL REFERENCES games(id),
    seq INTEGER NOT NULL,
    actor_id TEXT REFERENCES users(id),
    request_id TEXT,
    request_json TEXT,
    event_json TEXT NOT NULL,
    PRIMARY KEY(game_id,seq),
    UNIQUE(game_id,request_id)
);
CREATE TABLE rating_changes (
    game_id TEXT NOT NULL REFERENCES games(id),
    user_id TEXT NOT NULL REFERENCES users(id),
    before DOUBLE PRECISION NOT NULL,
    after DOUBLE PRECISION NOT NULL,
    PRIMARY KEY(game_id,user_id)
);
CREATE TABLE mobile_auth (
    hash TEXT PRIMARY KEY,
    provider TEXT NOT NULL,
    challenge TEXT NOT NULL,
    client_state TEXT NOT NULL,
    user_id TEXT REFERENCES users(id),
    session_hash TEXT,
    linking BOOLEAN NOT NULL,
    state_hash TEXT UNIQUE,
    code_hash TEXT UNIQUE,
    result_user TEXT REFERENCES users(id),
    error TEXT,
    expires_ms BIGINT NOT NULL
);
CREATE TABLE stream_tickets (
    hash TEXT PRIMARY KEY,
    game_id TEXT NOT NULL REFERENCES games(id),
    session_hash TEXT NOT NULL,
    expires_ms BIGINT NOT NULL
);
